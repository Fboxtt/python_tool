def build_exe(mode: str, version: str):
    """编译指定版本的EXE"""
    # 模式名称映射
    mode_names = {
        'factoryApp': '工厂版',
        'userApp': '用户版',
        'developerApp': '开发者版本',
        'firstuse': '首次使用版'
    }
    mode_name = mode_names.get(mode, mode)
    
    # 根据不同模式设置文件名
    if mode == 'firstuse':
        exe_name = "firstuse"
        output_dir = "dist/firstuse"
    elif mode == 'userApp':
        # 用户版：安培电池系统软件 + 版本号
        exe_name = f"安培电池系统软件v{version}"
        output_dir = f"dist/{mode_name}_v{version}"
    else:
        # 工厂版等其他版本：【模式】安培上位机v版本号
        exe_name = f"【{mode_name}】安培上位机v{version}"
        output_dir = f"dist/{mode_name}_v{version}"
    
    print(f"正在编译 {mode_name} 版本...")
    print(f"文件名: {exe_name}.exe")
    
    # 清理旧构建文件
    shutil.rmtree("build", ignore_errors=True)
    shutil.rmtree(output_dir, ignore_errors=True)
    
    # 生成运行时钩子文件
    with open(f"runtime_hook_enhanced_{mode}.py", "w", encoding='utf-8') as f:
        f.write(f"import os\nos.environ['APP_MODE'] = '{mode}'")
    
    # 构建参数
    args = [
        "enhanced_main_window.py",
        f"--name={exe_name}",
        "--onefile",
        "--windowed",
        "--icon=Ampere-Time-logo.ico",
        "--add-data=测试上位机.ui;.",
        "--add-data=monitor_interface.ui;.",
        "--add-data=build_version_info.py;.",
        "--add-data=builtin_hex.py;.",
        "--add-data=Ampere-Time-logo.ico;.",
        f"--distpath={output_dir}",
        f"--runtime-hook=runtime_hook_enhanced_{mode}.py",
        "--clean",
        "--noconfirm",
        # 排除PySide6以避免冲突
        "--exclude-module=PySide6",
        "--exclude-module=PySide6.QtCore",
        "--exclude-module=PySide6.QtGui", 
        "--exclude-module=PySide6.QtWidgets",
        "--exclude-module=shiboken6",
        # 包含WinRT模块（Windows 11蓝牙支持）
        "--hidden-import=winrt",
        "--hidden-import=winrt.windows.devices.bluetooth",
        "--hidden-import=winrt.windows.devices.radios",
        "--hidden-import=winrt.windows.foundation",
        "--hidden-import=winrt.windows.foundation.collections",
        "--hidden-import=winrt._winrt"
    ]
    
    # 调试版额外配置
    if mode in ["developerApp"]:
        args += [
            "--debug=all",
            "--console"  # 调试版显示控制台
        ]
    
    PyInstaller.__main__.run(args)
    os.remove(f"runtime_hook_enhanced_{mode}.py")  # 清理临时文件
    
    return output_dir, exe_name

def generate_builtin_hex():
    """扫描 src/ 目录，找第一个 .hex 文件，生成 builtin_hex.py"""
    import base64, glob
    hex_files = glob.glob('src/*.hex') + glob.glob('src/*.HEX')
    if not hex_files:
        print("⚠️  src/ 下未找到 HEX 文件，builtin_hex.py 不会更新")
        return False
    hex_path = hex_files[0]
    print(f"✅ 找到 HEX 文件: {hex_path}")
    with open(hex_path, 'rb') as f:
        raw = f.read()
    b64 = base64.b64encode(raw).decode('ascii')
    import os
    basename = os.path.basename(hex_path)
    chunk = 100
    lines = [
        '# -*- coding: utf-8 -*-',
        '# 内置固件（base64编码），由 build_enhance.py 自动生成，勿手动修改',
        f'# 源文件: {basename}',
        'BUILTIN_HEX_B64 = (',
    ]
    for i in range(0, len(b64), chunk):
        lines.append('    "' + b64[i:i+chunk] + '"')
    lines.append(')')
    lines.append('')
    with open('builtin_hex.py', 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    print(f"✅ builtin_hex.py 已生成 ({len(raw)} 字节 → {len(b64)} 字符 base64)")
    return True

def convert_ui_to_py(ui_file, py_file):
    """转换UI文件为Python文件 - 使用PyQt6"""
    try:
        # 使用PyQt6的pyuic6工具
        result = subprocess.run([
            'pyuic6', ui_file, '-o', py_file
        ], check=True, capture_output=True, text=True)
        
        print(f"UI转换成功: {ui_file} -> {py_file}")
        return True
    except subprocess.CalledProcessError as e:
        print(f"UI转换失败: {e}")
        print(f"错误输出: {e.stderr}")
        return False
    except FileNotFoundError:
        print("pyuic6 命令未找到，尝试使用 Python 模块方式...")
        try:
            # 使用 Python -m PyQt6.uic.pyuic 方式调用
            result = subprocess.run([
                sys.executable, '-m', 'PyQt6.uic.pyuic',
                ui_file, '-o', py_file
            ], check=True, capture_output=True, text=True)
            
            print(f"UI转换成功: {ui_file} -> {py_file}")
            return True
        except subprocess.CalledProcessError as e:
            print(f"Python模块方式也失败: {e}")
            return False

