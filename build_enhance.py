def get_version():
    """获取并递增版本号"""
    version_file = 'build_version_info.py'
    default_version = '1.0.0'
    
    # 读取当前版本号
    current_version = default_version
    if os.path.exists(version_file):
        try:
            with open(version_file, 'r', encoding='utf-8') as f:
                content = f.read()
                # 从文件中提取VERSION值
                import re
                match = re.search(r'VERSION = "([^"]+)"', content)
                if match:
                    current_version = match.group(1)
        except:
            current_version = default_version
    
    # 解析版本号
    try:
        parts = current_version.split('.')
        major, minor, patch = int(parts[0]), int(parts[1]), int(parts[2])
    except:
        major, minor, patch = 1, 0, 0
    
    # 递增修订号
    patch += 1
    new_version = f"{major}.{minor}.{patch}"
    
    print(f"✅ 版本号: {current_version} -> {new_version}")
    return new_version

def get_git_info():
    """获取Git信息"""
    git_info = {
        'commit_hash': 'Unknown',
        'commit_message': 'Unknown',
        'commit_author': 'Unknown',
        'commit_date': 'Unknown',
        'branch': 'Unknown'
    }
    
    try:
        # 获取当前分支
        result = subprocess.run(['git', 'rev-parse', '--abbrev-ref', 'HEAD'], 
                              capture_output=True, text=True, encoding='utf-8', 
                              errors='ignore', check=True)
        git_info['branch'] = result.stdout.strip()
        
        # 获取最新commit hash（短）
        result = subprocess.run(['git', 'rev-parse', '--short', 'HEAD'], 
                              capture_output=True, text=True, encoding='utf-8',
                              errors='ignore', check=True)
        git_info['commit_hash'] = result.stdout.strip()
        
        # 获取最新commit信息
        result = subprocess.run(['git', 'log', '-1', '--pretty=format:%s'], 
                              capture_output=True, text=True, encoding='utf-8',
                              errors='ignore', check=True)
        git_info['commit_message'] = result.stdout.strip() if result.stdout else 'Unknown'
        
        # 获取最新commit作者
        result = subprocess.run(['git', 'log', '-1', '--pretty=format:%an'], 
                              capture_output=True, text=True, encoding='utf-8',
                              errors='ignore', check=True)
        git_info['commit_author'] = result.stdout.strip() if result.stdout else 'Unknown'
        
        # 获取最新commit日期
        result = subprocess.run(['git', 'log', '-1', '--pretty=format:%ci'], 
                              capture_output=True, text=True, encoding='utf-8',
                              errors='ignore', check=True)
        git_info['commit_date'] = result.stdout.strip() if result.stdout else 'Unknown'
        
        print(f"✅ Git信息获取成功:")
        print(f"   分支: {git_info['branch']}")
        print(f"   Commit: {git_info['commit_hash']} - {git_info['commit_message']}")
        print(f"   作者: {git_info['commit_author']}")
        print(f"   提交时间: {git_info['commit_date']}")
        
    except subprocess.CalledProcessError as e:
        print(f"⚠️  无法获取Git信息（可能不在Git仓库中）: {e}")
    except FileNotFoundError:
        print("⚠️  Git命令未找到")
    except Exception as e:
        print(f"⚠️  获取Git信息时出错: {e}")
    
    return git_info

